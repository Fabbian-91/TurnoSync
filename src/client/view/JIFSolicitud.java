    private Runnable relojListener;

    private void iniciarReloj() {
        // Definir cómo actualizar el label
        relojListener = () -> LBFecha.setText(AppSession.getFechaHora());

        // Registrarse al reloj global
        AppSession.addListener(relojListener);

        // Inicializar inmediatamente
        LBFecha.setText(AppSession.getFechaHora());
    }

// Cuando cierres la vista, remover el listener
    @Override
    public void dispose() {
        if (relojListener != null) {
            AppSession.removeListener(relojListener);
        }
        super.dispose();
    }

    private void cargarComboTipos() {
        ArrayList<TipoSolicitud> lista = cargarLista();
        CbxTipoSolicitud.removeAllItems();

        if (AppSession.getRol() != Rol.EMPLEADO) {
            lista.remove(TipoSolicitud.TURNO_COMPLETADO);
            lista.remove(TipoSolicitud.CAMBIO_ROL);
        }

        for (TipoSolicitud t : lista) {
            CbxTipoSolicitud.addItem(t.toString());
        }
    }

    private ArrayList<TipoSolicitud> cargarLista() {
        return new ArrayList<>(List.of(TipoSolicitud.values()));
    }

   
