    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
        try {
            String usuario = JTUsuario.getText().trim();
            String detalle = jTextArea1.getText().trim();
            String tipoSeleccionado = CbxTipoSolicitud.getSelectedItem().toString();

            TipoSolicitud tipo = TipoSolicitud.valueOf(tipoSeleccionado);

            Usuario u = new Usuario();
            u.setUsername(usuario);

            Peticion p = new Peticion();
            p.setUsuario(u);
            p.setTipo(tipo);
            p.setDetalle(detalle);

            Result<Void> result = peticionController.sendPeticion(p);

            if (result.ok) {
                javax.swing.JOptionPane.showMessageDialog(
                        this,
                        result.message,
                        "Éxito",
                        javax.swing.JOptionPane.INFORMATION_MESSAGE
                );

                jTextArea1.setText("");
                CbxTipoSolicitud.setSelectedIndex(0);

            } else {
                javax.swing.JOptionPane.showMessageDialog(
                        this,
                        result.message,
                        "Error",
                        javax.swing.JOptionPane.ERROR_MESSAGE
                );
            }

        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    e.getMessage(),
                    "Error",
                    javax.swing.JOptionPane.ERROR_MESSAGE
            );
        }
    }//GEN-LAST:event_jButton4ActionPerformed


