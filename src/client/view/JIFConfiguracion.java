    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
        String nueva = JTNuevaContraseña.getText().trim();
        String confirmar = JTConfirmar.getText().trim();

        if (nueva.isEmpty() || confirmar.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Debe completar ambos campos.",
                    "Aviso",
                    javax.swing.JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        if (!nueva.equals(confirmar)) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Las contraseñas no coinciden.",
                    "Aviso",
                    javax.swing.JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        Result<Void> result = controller.updatePassword(AppSession.getUser(), AppSession.getName(), nueva, confirmar);

        if (result.ok) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    result.message,
                    "Éxito",
                    javax.swing.JOptionPane.INFORMATION_MESSAGE
            );

            JTNuevaContraseña.setText("");
            JTConfirmar.setText("");

        } else {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    result.message,
                    "Error",
                    javax.swing.JOptionPane.ERROR_MESSAGE
            );
        }

        limpiarCampos();

    }//GEN-LAST:event_jButton4ActionPerformed


