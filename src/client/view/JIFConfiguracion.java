    private Runnable relojListener;

    private void iniciarReloj() {
        // Definir cómo actualizar el label
        relojListener = () -> LBFecha.setText(AppSession.getFechaHora());

        // Registrarse al reloj global
        AppSession.addListener(relojListener);

        // Inicializar inmediatamente
        LBFecha.setText(AppSession.getFechaHora());
    }

// Cuando cierres la vista, remover el listener
    @Override
    public void dispose() {
        if (relojListener != null) {
            AppSession.removeListener(relojListener);
        }
        super.dispose();
    }

    private void inicializarTextFiel() {
        TxfNombreSistema.setEditable(false);
        TxfNombreUsuario.setEditable(false);
        TxfUserEmail.setEditable(false);

        TxfNombreSistema.setText("TunoSync");
        TxfNombreUsuario.setText(AppSession.getName());
        TxfUserEmail.setText(AppSession.getUser());
    }

    private void limpiarCampos() {
        JTConfirmar.setText("");
        JTNuevaContraseña.setText("");
    }
